#!/usr/bin/env python3
"""usage: attack.py PROJECT_DIR  — independent attack on a built `kvstore` package."""
import sys, os, time
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
from svc import Svc
proj = sys.argv[1]
s = Svc(proj, "kvstore", {"KV_TOKENS": "tokA:acme,tokB:globex", "KV_DB": "{tmp}/a.db"}, 8814, grants="net,sql,env,fs_write,time", port_env="KV_PORT")
if not s.up: s.note("server starts with grants net,sql,env,fs_write,time", False, "did not start"); s.finish()
A, B = {"Authorization": "Bearer tokA"}, {"Authorization": "Bearer tokB"}
c = s.check
def put(h, key, value="v", ttl=None, extra=None):
    b = {"value": value}
    if ttl is not None: b["ttl_seconds"] = ttl
    b.update(extra or {})
    return s.req("PUT", f"/kv/{key}", h, b)
# 1. authentication
r_none = c("no token -> 401", s.req("GET", "/kv/a"), 401)
r_unk = c("unknown token -> 401", s.req("GET", "/kv/a", {"Authorization": "Bearer nope"}), 401, excludes="nope")
c("malformed (Basic) -> 401", s.req("GET", "/kv/a", {"Authorization": "Basic dG9rQQ=="}), 401)
c("scheme only -> 401", s.req("GET", "/kv/a", {"Authorization": "Bearer"}), 401)
c("trailing space must not crash (200/404/401)", s.req("GET", "/kv/a", {"Authorization": "Bearer tokA "}), [401, 404])
c("PUT without token -> 401", s.req("PUT", "/kv/a", None, {"value": "v"}), 401)
c("DELETE without token -> 401", s.req("DELETE", "/kv/a"), 401)
c("list without token -> 401", s.req("GET", "/kv"), 401)
s.note("missing and unknown token give the identical 401 body", r_none[1] == r_unk[1], f"{r_none[1][:50]!r} vs {r_unk[1][:50]!r}")
# 2. basic put/get/delete
c("PUT new key -> 201", put(A, "k1", "hello"), 201, test=lambda j: j["key"] == "k1" and j["value"] == "hello")
c("PUT existing key -> 200", put(A, "k1", "hello2"), 200)
c("GET -> value, permanent has null expires_in", s.req("GET", "/kv/k1", A), 200, test=lambda j: j["value"] == "hello2" and j["expires_in"] is None)
c("PUT empty value -> 201", put(A, "empty", ""), 201)
c("GET empty value -> 200 with empty string", s.req("GET", "/kv/empty", A), 200, test=lambda j: j["value"] == "")
c("GET missing -> 404", s.req("GET", "/kv/nope", A), 404)
c("DELETE existing -> 204", s.req("DELETE", "/kv/empty", A), 204)
c("GET after DELETE -> 404", s.req("GET", "/kv/empty", A), 404)
c("DELETE missing -> 404", s.req("DELETE", "/kv/empty", A), 404)
c("value with quotes and SQL stored verbatim", put(A, "q", "it's ' OR '1'='1 \"x\" \\ \n"), 201)
c("value read back verbatim", s.req("GET", "/kv/q", A), 200, test=lambda j: j["value"] == "it's ' OR '1'='1 \"x\" \\ \n")
c("non-ASCII value round-trips", put(A, "uni", "é日本🙂"), 201)
c("non-ASCII value read back", s.req("GET", "/kv/uni", A), 200, test=lambda j: j["value"] == "é日本🙂")
# 3. isolation
c("B cannot read A's key: 404", s.req("GET", "/kv/k1", B), 404)
c("B cannot delete A's key: 404", s.req("DELETE", "/kv/k1", B), 404)
c("A's key survives B's delete", s.req("GET", "/kv/k1", A), 200, test=lambda j: j["value"] == "hello2")
c("B PUT the same key -> 201 (separate key space)", put(B, "k1", "bee"), 201)
c("A still sees its own value", s.req("GET", "/kv/k1", A), 200, test=lambda j: j["value"] == "hello2")
c("B sees its own value", s.req("GET", "/kv/k1", B), 200, test=lambda j: j["value"] == "bee")
c("B's list shows only B's keys", s.req("GET", "/kv", B), 200, test=lambda j: j["keys"] == ["k1"])
s.note("foreign key and missing key give the identical 404", s.req("GET", "/kv/q", B) == s.req("GET", "/kv/zzz-missing", B))
# 4. key validation
for bad in ["UPPER", "a b", "a/b", "a%20b", "x" * 65, "a;b", "%27", "..%2Fetc", "a'b"]:
    c(f"GET key {bad[:20]!r} -> 404", s.req("GET", f"/kv/{bad}", A), 404)
    c(f"PUT key {bad[:20]!r} -> 400 or 404", put(A, bad), [400, 404])
c("PUT key of 64 chars -> 201", put(A, "k" * 64), 201)
c("PUT key with . _ - -> 201", put(A, "a.b_c-d"), 201)
# 5. body validation
c("value 1001 chars -> 400", put(A, "v1", "a" * 1001), 400)
c("value 1000 chars -> 201", put(A, "v2", "a" * 1000), 201)
c("missing value -> 400", s.req("PUT", "/kv/v3", A, {}), 400)
c("value not a string -> 400", s.req("PUT", "/kv/v3", A, {"value": 5}), 400)
c("ttl 0 -> 400", put(A, "t0", ttl=0), 400)
c("ttl -1 -> 400", put(A, "t0", ttl=-1), 400)
c("ttl 86401 -> 400", put(A, "t0", ttl=86401), 400)
c("ttl float -> 400", s.req("PUT", "/kv/t0", A, {"value": "v", "ttl_seconds": 1.5}), 400)
c("ttl string -> 400", s.req("PUT", "/kv/t0", A, {"value": "v", "ttl_seconds": "5"}), 400)
c("ttl 86400 -> 201", put(A, "t1", ttl=86400), 201)
c("unknown field -> 400", put(A, "u1", extra={"extra": 1}), 400)
c("invalid JSON -> 400", s.req("PUT", "/kv/u2", A, raw_body="{nope"), 400)
c("array body -> 400", s.req("PUT", "/kv/u2", A, raw_body="[1]"), 400)
c("empty body -> 400", s.req("PUT", "/kv/u2", A, raw_body=""), 400)
c("body of 5000 bytes -> 413", s.req("PUT", "/kv/big", A, raw_body='{"value":"' + "a" * 5000 + '"}'), 413)
c("body of 200000 bytes -> 413", s.req("PUT", "/kv/big", A, raw_body='{"value":"' + "a" * 200000 + '"}'), 413)
c("rejected PUTs stored nothing", s.req("GET", "/kv/u1", A), 404)
# 6. listing
for k in ["app.one", "app.two", "app_three", "apx", "zeta"]: put(A, k)
c("list: ascending, own keys", s.req("GET", "/kv?limit=100", A), 200, test=lambda j: j["keys"] == sorted(j["keys"]) and "app.one" in j["keys"])
c("prefix 'app.' lists exactly the matching keys", s.req("GET", "/kv?prefix=app.", A), 200, test=lambda j: j["keys"] == ["app.one", "app.two"])
c("prefix '_' is not a wildcard", s.req("GET", "/kv?prefix=app_", A), 200, test=lambda j: j["keys"] == ["app_three"])
c("prefix with % is invalid or literal, never a wildcard", s.req("GET", "/kv?prefix=%25", A), [200, 400], test=lambda j: j.get("keys", []) == [] if isinstance(j, dict) and "keys" in j else True)
c("prefix SQL injection -> 400", s.req("GET", "/kv?prefix=a'%20OR%20'1'='1", A), 400)
c("prefix of 65 chars -> 400", s.req("GET", "/kv?prefix=" + "a" * 65, A), 400)
c("prefix matching nothing -> empty list", s.req("GET", "/kv?prefix=nomatch", A), 200, test=lambda j: j["keys"] == [])
c("limit=0 -> 400", s.req("GET", "/kv?limit=0", A), 400)
c("limit=101 -> 400", s.req("GET", "/kv?limit=101", A), 400)
c("limit=abc -> 400", s.req("GET", "/kv?limit=abc", A), 400)
c("limit=2 -> exactly 2 keys", s.req("GET", "/kv?limit=2", A), 200, test=lambda j: len(j["keys"]) == 2)
# 7. expiry (real clock)
c("PUT with ttl 2 -> 201", put(A, "ttl-key", "soon", ttl=2), 201)
c("GET shows expires_in 1 or 2", s.req("GET", "/kv/ttl-key", A), 200, test=lambda j: j["expires_in"] in (1, 2))
c("PUT permanent key for contrast", put(A, "perm-key", "stay"), 201)
c("PUT ttl 2 then replace without ttl makes it permanent", put(A, "swap", "x", ttl=2), 201)
c("replace without ttl -> 200", put(A, "swap", "y"), 200)
c("PUT ttl 86400 for contrast", put(A, "long-key", "x", ttl=86400), 201)
time.sleep(3.2)
c("expired entry -> 404", s.req("GET", "/kv/ttl-key", A), 404)
c("expired entry absent from the list", s.req("GET", "/kv?limit=100", A), 200, excludes="ttl-key")
c("expired entry DELETE -> 404", s.req("DELETE", "/kv/ttl-key", A), 404)
c("permanent entry survives", s.req("GET", "/kv/perm-key", A), 200)
c("replaced-to-permanent entry survives", s.req("GET", "/kv/swap", A), 200, test=lambda j: j["expires_in"] is None)
c("long ttl entry survives with a large expires_in", s.req("GET", "/kv/long-key", A), 200, test=lambda j: 86000 < j["expires_in"] <= 86400)
c("PUT on an expired key -> 201 (as new)", put(A, "ttl-key", "again"), 201)
# 8. deployment
lo = s.listens_on_loopback_only()
s.note("listens on loopback only by default", lo is True, "not loopback-only" if lo is False else "could not tell")
c("still alive after all of the above", s.req("GET", "/kv/perm-key", A), 200)
s.finish()
